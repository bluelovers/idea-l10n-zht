import { renderMarkdown } from './md';
import { readFileSync } from 'fs';
import { join } from 'upath2';
import { __root } from '../test/__root';
import { PluginXml } from './util/xml/plugin-xml';
import { insertAfterObjectKey } from './util/insertAfterObjectKey';

/**
 * 更新外掛的 plugin.xml 元資料（ID、名稱、描述、版本資訊等）
 * Update plugin.xml metadata (ID, name, description, version info, etc.)
 *
 * 將 README.md 轉為 HTML 作為外掛描述，並設定外掛的基本識別資訊。
 * 此函式只在處理 plugin.xml 檔案時被呼叫
 * Converts README.md to HTML as plugin description, and sets basic plugin identification info.
 * This function is only called when processing plugin.xml files
 *
 * @param content_new - 原始的 plugin.xml 內容 / Original plugin.xml content
 * @returns 更新後的 plugin.xml XML 字串 / Updated plugin.xml XML string
 */
export function updateMeta(content_new: string)
{
	// @ts-ignore
	const html = renderMarkdown(readFileSync(join(__root, 'README.md')));

	const obj = new PluginXml(content_new);

	/**
	 * 移除 Till-Build 設定（由 CI/CD 流程動態生成）
	 * Remove Till-Build configuration (dynamically generated by CI/CD pipeline)
	 */
	obj.removeUntilBuild();

	/** 設定外掛唯一識別碼 / Set plugin unique identifier */
	obj.id = 'com.intellij.zh-tw';

	/** 設定外掛顯示名稱（中英文雙語）/ Set plugin display name (bilingual Chinese-English) */
	obj.name = `Chinese (Traditional) Language Pack / 繁體中文語言包`;

	// from 2024.2 EAP
	/** 設定語言代碼為繁體中文 / Set locale to Traditional Chinese */
	obj.locale = 'zh-TW';

	/** 設定外掛廠商資訊 / Set plugin vendor information */
	obj.root['vendor'] = {
		'@url': 'https://github.com/bluelovers/idea-l10n-zht',
		'#': 'bluelovers',
	}

	/**
	 * 將 vendor 欄位插入到 category 之後，保持 XML 結構的可讀性
	 * Insert vendor field after category to maintain XML structure readability
	 */
	insertAfterObjectKey(obj.root, 'category', 'Language Pack', 'vendor');

	/** 設定外掛描述（來自 README.md 轉換的 HTML）/ Set plugin description (HTML converted from README.md) */
	obj.description = html;

	/** 設定變更紀錄連結 / Set changelog link */
	obj.changeNnotes = `See <a href="https://github.com/bluelovers/idea-l10n-zht/commits/master">https://github.com/bluelovers/idea-l10n-zht/commits/master</a> or <a href="https://github.com/bluelovers/idea-l10n-zht/blob/master/CHANGELOG.md">CHANGELOG.md</a>`;

	/**
	 * 移除 incompatible-with 欄位，避免版本相容性檢查衝突
	 * Remove incompatible-with field to avoid version compatibility check conflicts
	 */
	delete obj.root['incompatible-with'];

	return obj.toString();
}
