/**
 * 從 JetBrains 插件市集取得簡體中文語言包最新版本
 * Fetch the latest zh-CN language pack version from JetBrains Plugin Marketplace
 *
 * 透過 JetBrains API 查詢簡體中文插件 (ID: 13710) 的最新版本，
 * 與本地記錄的版本比較後，若有新版本則自動更新 link-of-zh-cn.ts 檔案。
 * Queries the JetBrains API for the zh-CN plugin (ID: 13710) latest version,
 * compares with the locally recorded version, and updates link-of-zh-cn.ts if a new version exists.
 */
import { outputFile } from 'fs-extra';
import { join } from 'upath2';
import { __root } from '../test/__root';
import fetch from 'cross-fetch';
import { __plugin_zh_cn_id } from '../lib/const/link-of-zh-cn';
import { console } from 'debug-color2';
import Bluebird from 'bluebird';
import type { IVersionApiResult } from '../lib/const/version-map';
import {
	_getVersionDownloadByVersion,
	_getVersionInfoBySeries,
	generateVersionMap,
	getLatestSeries,
} from '../lib/util/version-map';

export default Bluebird.resolve(fetch('https://plugins.jetbrains.com/api/plugins/13710/updates?channel=&size=5'))
	.then((res) =>
	{
		return res.json() as any as IVersionApiResult;
	})
	.then(generateVersionMap)
	.then((data) =>
	{
		const sv = getLatestSeries(data);
		const row = _getVersionInfoBySeries(sv, data);

		const id = row.id.toString();
		const version = row.version.toString();

		/**
		 * 比較遠端最新版本與本地記錄的版本 ID
		 * 若不同則代表有新版本可用，需更新本地版本資訊檔
		 * Compare remote latest version with locally recorded version ID.
		 * If different, a new version is available and the local version info file needs updating.
		 */
		if (__plugin_zh_cn_id !== id)
		{
			console.success(`發現新版本 #${id} version: ${version}`);

			const __plugin_zh_cn_download = _getVersionDownloadByVersion(version, data);

			/**
			 * 將新版本資訊寫入 link-of-zh-cn.ts，
			 * 供後續建構流程（下載、轉換、打包）使用
			 * Write new version info to link-of-zh-cn.ts
			 * for subsequent build pipeline (download, convert, package) to use
			 */
			return outputFile(join(__root, 'lib/const/link-of-zh-cn.ts'), `
/**
 * 此檔案為腳本自動生成，請勿手動修改
 * This file is automatically generated by script, please do not modify it manually
 */

/**
 * 中文（簡體）語言包的插件 ID
 * Plugin ID for Chinese (Simplified) language pack
 *
 * @default '${id}'
 * @deprecated 已棄用，請使用動態版本管理 / Deprecated, use dynamic version management
 */
export const __plugin_zh_cn_id: string = '${id}';

/**
 * 中文（簡體）語言包的版本系列
 * Version series for Chinese (Simplified) language pack
 *
 * @default '${sv}'
 * @deprecated 已棄用，請使用動態版本管理 / Deprecated, use dynamic version management
 */
export const __plugin_zh_cn_series: string = '${sv}';
/**
 * 中文（簡體）語言包的版本號
 * Version number for Chinese (Simplified) language pack
 *
 * @default '${version}'
 * @deprecated 已棄用，請使用動態版本管理 / Deprecated, use dynamic version management
 */
export const __plugin_zh_cn_version: string = '${version}';

/**
 * 中文（簡體）語言包的下載連結
 * Download URL for Chinese (Simplified) language pack
 *
 * @see ${__plugin_zh_cn_download}
 * @deprecated 已棄用，請使用動態版本管理 / Deprecated, use dynamic version management
 */
export const __plugin_zh_cn_download: string = '${__plugin_zh_cn_download}';

`);
		}

		console.gray(`沒有發現新版本`);
	})
	.catch((e) =>
	{
		console.error(`嘗試偵測新版本時發生錯誤`);
		console.error(e);
	})
;
